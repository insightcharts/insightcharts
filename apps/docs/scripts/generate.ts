// Scans packages/insightcharts/src/{atoms,molecules,templates}/*.tsx and writes
//   src/generated/catalog.json    every component's meta, its `examples` export and source facts
//   src/generated/components.tsx  a client module mapping name -> component + examples
// Every catalogue page, the sidebar, search and the cross-links are derived from these two
// files, so a new component file appears in the docs with no docs edits. Runs before
// `dev` and `build`; `scripts/dev.mjs` re-runs it when a component file changes.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const lib = join(here, "../../../packages/insightcharts");
const src = join(lib, "src");
const outDir = join(here, "../src/generated");
const LEVELS = ["atom", "molecule", "template"] as const;

interface Meta {
  name: string;
  component: string;
  title: string;
  level: (typeof LEVELS)[number];
  category: string;
  description: string;
  whenToUse?: string;
  avoid?: string;
  props: { name: string; type: string; description: string; default?: string; required?: boolean }[];
  composes?: string[];
  example?: Record<string, unknown>;
}

interface Entry extends Meta {
  /** Path relative to packages/insightcharts/src, e.g. `atoms/bar-chart`. */
  file: string;
  /** Built with defineChart (accepts the common chart props). */
  chart: boolean;
  /** Present in the client module. False when the source file could not be imported. */
  live: boolean;
  examples: { title: string; props: Record<string, unknown> }[];
}

// Functions and other non-JSON values cannot be shown as a spec; mark them so the code
// tab can say so instead of silently dropping the prop.
const toJson = (value: unknown) => JSON.parse(JSON.stringify(value, (_k, v) => (typeof v === "function" ? "[function]" : v)) ?? "null");

let manifest: Meta[] = [];
try {
  manifest = JSON.parse(readFileSync(join(lib, "manifest.json"), "utf8")).components ?? [];
} catch {
  /* the manifest is optional: source is the primary input */
}

const entries: Entry[] = [];
const warnings: string[] = [];

for (const level of LEVELS) {
  const dir = join(src, `${level}s`);
  if (!existsSync(dir)) continue;
  const files = readdirSync(dir)
    .filter((f) => /\.tsx$/.test(f) && !f.startsWith("index.") && !f.startsWith("_") && !f.endsWith(".test.tsx"))
    .sort();
  for (const f of files) {
    const base = f.replace(/\.tsx$/, "");
    const file = `${level}s/${base}`;
    const text = readFileSync(join(dir, f), "utf8");
    const chart = /\bdefineChart\s*[<(]/.test(text);
    try {
      const mod = (await import(pathToFileURL(join(dir, f)).href)) as Record<string, unknown>;
      const metas = Object.values(mod)
        .map((v) => (v as { meta?: Meta } | null)?.meta)
        .filter((m): m is Meta => !!m?.name);
      if (!metas.length) {
        warnings.push(`${file}: no export carries meta, skipped`);
        continue;
      }
      const raw = (mod.examples ?? {}) as Record<string, Record<string, unknown>>;
      for (const meta of metas) {
        // `examples` belongs to the component the file is named after.
        const own = meta.name === base || metas.length === 1;
        entries.push({
          ...toJson(meta),
          props: meta.props ?? [],
          file,
          chart,
          live: true,
          examples: own ? Object.entries(raw).map(([title, props]) => ({ title, props: toJson(props) })) : [],
        });
      }
    } catch (error) {
      // A file that is mid-edit must not take the whole site down: fall back to the last
      // manifest entry (no live preview) and say so.
      const fallback = manifest.find((m) => m.name === base);
      warnings.push(`${file}: import failed (${(error as Error).message.split("\n")[0]})${fallback ? ", using manifest.json entry without a live preview" : ", skipped"}`);
      if (fallback) entries.push({ ...fallback, file, chart, live: false, examples: [] });
    }
  }
}

const order = { atom: 0, molecule: 1, template: 2 };
entries.sort((a, b) => order[a.level] - order[b.level] || a.name.localeCompare(b.name));

const seen = new Set<string>();
const unique = entries.filter((e) => (seen.has(e.name) ? (warnings.push(`duplicate component name "${e.name}" in ${e.file}, ignored`), false) : (seen.add(e.name), true)));

const live = unique.filter((e) => e.live);
const files = [...new Set(live.map((e) => e.file))];
const ident = (file: string) => `m${files.indexOf(file)}`;
const client = `"use client";
// Generated by scripts/generate.ts. Do not edit.
import type { ComponentType } from "react";
${files.map((file) => `import * as ${ident(file)} from "@ic/${file}";`).join("\n")}

export interface RegistryEntry {
  Component: ComponentType<any>;
  examples: Record<string, Record<string, unknown>>;
}

const pick = (mod: Record<string, unknown>, name: string): RegistryEntry => ({
  Component: Object.values(mod).find((v) => (v as { meta?: { name?: string } } | null)?.meta?.name === name) as ComponentType<any>,
  examples: (mod.examples ?? {}) as Record<string, Record<string, unknown>>,
});

export const registry: Record<string, RegistryEntry> = {
${live.map((e) => `  ${JSON.stringify(e.name)}: pick(${ident(e.file)}, ${JSON.stringify(e.name)}),`).join("\n")}
};
`;

// The props every chart accepts are documented once, from the CommonChartProps interface
// itself: name, type and JSDoc are read straight out of core/define.tsx.
function commonProps() {
  const text = readFileSync(join(src, "core/define.tsx"), "utf8");
  const body = text.match(/export interface CommonChartProps \{([\s\S]*?)\n\}/)?.[1] ?? "";
  const out: { name: string; type: string; description: string }[] = [];
  const re = /(?:\/\*\*([\s\S]*?)\*\/\s*)?^\s*(\w+)\??:\s*([^;]+);/gm;
  for (const m of body.matchAll(re)) {
    const description = (m[1] ?? "")
      .split("\n")
      .map((l) => l.replace(/^\s*\*?\s?/, "").trim())
      .join(" ")
      .trim();
    out.push({ name: m[2], type: m[3].replace(/\s+/g, " ").trim(), description });
  }
  return out;
}

const write = (name: string, content: string) => {
  const path = join(outDir, name);
  // Leave untouched files alone so the dev server does not reload for nothing.
  if (existsSync(path) && readFileSync(path, "utf8") === content) return;
  writeFileSync(path, content);
};
mkdirSync(outDir, { recursive: true });
write("catalog.json", JSON.stringify({ components: unique, commonProps: commonProps() }, null, 2) + "\n");
write("components.tsx", client);

for (const w of warnings) console.warn(`[docs:generate] ${w}`);
const count = (l: string) => unique.filter((e) => e.level === l).length;
console.log(`[docs:generate] ${unique.length} components (${count("atom")} atoms, ${count("molecule")} molecules, ${count("template")} templates), ${unique.reduce((n, e) => n + e.examples.length, 0)} extra examples`);
