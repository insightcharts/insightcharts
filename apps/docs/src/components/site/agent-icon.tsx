/** How long each mark stays, in ms. */
const DWELL = 2200;

// One clock for the whole page, so every button shows the same mark at the same time.
const listeners = new Set<() => void>();
let timer: ReturnType<typeof setInterval> | undefined;
let index = 0;

function subscribe(listener: () => void) {
  listeners.add(listener);
  const still = typeof matchMedia === "function" && matchMedia("(prefers-reduced-motion: reduce)").matches;
  if (!timer && !still) {
    timer = setInterval(() => {
      if (document.hidden) return;
      index = (index + 1) % AGENTS.length;
      listeners.forEach((l) => l());
    }, DWELL);
  }
  return () => {
    listeners.delete(listener);
    if (!listeners.size && timer) {
      clearInterval(timer);
      timer = undefined;
    }
  };
}

/**
 * The icon on every "Copy agent instructions" control: the agents' marks, one at a time,
 * cross-fading. It holds still on the first mark for readers who prefer reduced motion.
 */
export function AgentIcon({ className }: { className?: string }) {
  const active = useSyncExternalStore(
    subscribe,
    () => index,
    () => 0,
  );
  return (
    <span aria-hidden className={cn("relative inline-block size-4 shrink-0", className)}>
      {AGENTS.map((a, i) => (
        <svg
          key={a.name}
          viewBox={a.viewBox}
          className={cn("absolute inset-0 size-full transition-[opacity,transform] duration-500 ease-out", i === active ? "scale-100 opacity-100" : "scale-75 opacity-0")}
          style={{ color: a.color ?? undefined }}
          fill="currentColor"
        >
          <path d={a.d} fillRule={a.evenodd ? "evenodd" : undefined} clipRule={a.evenodd ? "evenodd" : undefined} />
        </svg>
      ))}
    </span>
  );
}

