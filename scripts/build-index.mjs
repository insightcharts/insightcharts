// Regenerates src/{atoms,molecules,templates}/index.ts from the files present, so adding a
// component never means editing a shared file. Run: pnpm index
// Every named export is re-exported except `examples` (each file has one, for the gallery
// and docs) and names starting with an underscore.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const src = fileURLToPath(new URL("../packages/insightcharts/src/", import.meta.url));
const VALUE = /^export\s+(?:const|function|class|let)\s+([A-Za-z_$][\w$]*)/gm;
const TYPE = /^export\s+(?:interface|type)\s+([A-Za-z_$][\w$]*)/gm;
const skip = (n) => n === "examples" || n.startsWith("_");

// Components (value exports carrying `meta`) per level, for the spec registry below.
const registryImports = [];
const registryNames = [];

for (const dir of ["atoms", "molecules", "templates"]) {
  const files = readdirSync(src + dir)
    .filter((f) => /\.tsx?$/.test(f) && !f.startsWith("index.") && !f.startsWith("_") && !/\.test\.tsx?$/.test(f))
    .sort();
  const seen = new Map();
  const lines = [];
  for (const f of files) {
    const code = readFileSync(`${src}${dir}/${f}`, "utf8");
    const mod = `./${f.replace(/\.tsx?$/, "")}`;
    const values = [...code.matchAll(VALUE)].map((m) => m[1]).filter((n) => !skip(n));
    const types = [...code.matchAll(TYPE)].map((m) => m[1]).filter((n) => !skip(n));
    for (const n of [...values, ...types]) {
      if (seen.has(n)) {
        console.error(`Duplicate export "${n}" in ${dir}/${f} and ${dir}/${seen.get(n)}. Rename one, or prefix a file-private helper with "_" or drop its "export".`);
        process.exitCode = 1;
      }
      seen.set(n, f);
    }
    // The component is the value export named after the file: bar-chart.tsx exports BarChart.
    const pascal = f.replace(/\.tsx?$/, "").replace(/(^|-)([a-z0-9])/g, (_m, _d, c) => c.toUpperCase());
    const components = values.filter((n) => n === pascal);
    if (components.length) {
      registryImports.push(`import { ${components.join(", ")} } from "./${dir}/${f.replace(/\.tsx?$/, "")}";`);
      registryNames.push(...components);
    }
    if (values.length) lines.push(`export { ${values.join(", ")} } from "${mod}";`);
    if (types.length) lines.push(`export type { ${types.join(", ")} } from "${mod}";`);
  }
  writeFileSync(`${src}${dir}/index.ts`, `// Generated by scripts/build-index.mjs. Do not edit.\n${lines.length ? lines.join("\n") : "export {};"}\n`);
  console.log(`${dir}: ${files.length}`);
}

// The list <Insight> registers. It lives inside a function so that an app which never
// renders a spec can tree-shake every component it does not import by name.
writeFileSync(
  `${src}components.generated.ts`,
  `// Generated by scripts/build-index.mjs. Do not edit.\n${registryImports.join("\n")}\n\nexport function allComponents(): unknown[] {\n  return [${registryNames.join(", ")}];\n}\n`,
);
console.log(`registry list: ${registryNames.length}`);
